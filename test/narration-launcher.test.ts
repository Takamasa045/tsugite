import { copyFile, mkdir, mkdtemp, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import { startWorkflowViewerLauncher, type WorkflowViewerLauncher } from "../src/viewer/launcher.js";
import { writeBillingQuotes, loadGenerationBilling, billingApprovalDigest } from "../src/adapters/billing.js";
import { loadAdapterDefinition } from "../src/adapters/registry.js";
import { projectSchema } from "../src/project/schema.js";
import { createPlannedState, markGateAwaiting, recordGateDecision, writeState } from "../src/orchestrator/state.js";
import { fixturePermit } from "./fixtures/elevenlabs-v4-authority.mjs";
import { initialGeneratedReceipt } from "../adapters/elevenlabs-v4/receipts.mjs";
const roots: string[] = [], launchers: WorkflowViewerLauncher[] = [];
afterEach(async () => { await Promise.all(launchers.splice(0).map(l => l.close())); for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); vi.unstubAllEnvs(); });
describe("narration launcher guards (no provider)", () => {
  it("rejects stale cards and unknown receipts on the server and rereads the local state", async () => {
    const root = await realpath(await mkdtemp(join(tmpdir(), "tsugite-narration-launcher-"))); roots.push(root);
    const projects = join(root, "projects"), projectRoot = join(projects, "voice"), run = join(projectRoot, "dist", "fixture"), bundle = join(root, "bundle");
    await mkdir(projectRoot, { recursive: true }); await mkdir(join(bundle, "assets"), { recursive: true });
    await writeFile(join(bundle, "index.html"), '<!doctype html><html><head><title>Fixture</title></head><body><div id="root"></div></body></html>'); await writeFile(join(bundle, "assets", "app.js"), "");
    await copyFile(resolve("fixtures/media/render-001.mp4"), join(projectRoot, "clip.mp4"));
    const manifest = JSON.parse(await readFile("fixtures/manifests/render-local.valid.json", "utf8")); manifest.clips[0].src = "clip.mp4"; manifest.captions = [];
    await writeFile(join(projectRoot, "manifest.json"), JSON.stringify(manifest));
    const request = { id: "voice", operation: "voice" as const, output_kind: "audio" as const, model: "eleven_v4", prompt: "Connection test.", params: { voice_id: "fixture-voice" } };
    const project = projectSchema.parse({ name: "fixture", slug: "fixture", manifest: "manifest.json", dist_dir: "dist", edit: { backend: "remotion" }, generation: { connection: "elevenlabs", requests: [request] } });
    const config = join(projectRoot, "project.yaml"); await writeFile(config, JSON.stringify(project));
    vi.stubEnv("ELEVENLABS_MCP_ACCESS_TOKEN", "fixture-never-sent");
    const adapter = await loadAdapterDefinition("elevenlabs-v4"), permit = fixturePermit(request);
    await writeBillingQuotes(run, [{ request_id: request.id, quote: permit.quote }], { schema_version: 1, kind: "tsugite.billing-context", project_root: projectRoot, project_slug: project.slug });
    const state = recordGateDecision(markGateAwaiting(createPlannedState("fixture"), "gate_1"), "gate_1", "approved");
    state.gates.gate_1.approved_input_digest = permit.gate_approval_digest;
    state.gates.gate_1.billing_approval_digest = billingApprovalDigest(await loadGenerationBilling(config, project, adapter));
    await writeState(join(projectRoot, "dist"), state);
    let finish!: (value: unknown) => void;
    const pending = new Promise(done => { finish = done; }), runGeneration = vi.fn(async () => pending);
    let canStart = true;
    const launcher = await startWorkflowViewerLauncher({ projectsDir: projects, bundleDir: bundle, linkProjectShelves: false, runGeneration, canStartWork: () => canStart, port: 0 }); launchers.push(launcher);
    const listing = await fetch(`${launcher.url}/api/projects`).then(r => r.json()), id = listing.projects[0].id;
    const canvas = async () => (await fetch(`${launcher.url}/api/projects/${id}/generation-canvas`).then(r => r.json())).canvas;
    expect((await canvas()).narrationStatus).toMatchObject({ state: "ready", can_generate: true });
    const post = (action: string, digest?: string) => fetch(`${launcher.url}/api/projects/${id}/${action}`, { method: "POST", headers: { origin: launcher.url, "x-tsugite-token": launcher.token, "content-type": "application/json" }, body: JSON.stringify(digest ? { approval_digest: digest } : {}) });
    expect((await post("generate")).status).toBe(409);
    expect((await post("generate", "b".repeat(64))).status).toBe(409); expect(runGeneration).not.toHaveBeenCalled();
    const a = post("generate", permit.gate_approval_digest), b = post("generate", permit.gate_approval_digest);
    try {
      await vi.waitFor(() => expect(runGeneration).toHaveBeenCalledOnce());
      expect((await Promise.race([a, b])).status).toBe(409);
    } finally { finish({ ok: true }); }
    expect((await Promise.all([a, b])).map(r => r.status).sort()).toEqual([200, 409]);
    expect(runGeneration).toHaveBeenCalledOnce();
    const directory = join(run, "assets/elevenlabs-v4"); await mkdir(directory, { recursive: true });
    const receipt = initialGeneratedReceipt({ request, run_id: "fixture" }, permit, { kind: "creative" });
    await writeFile(join(directory, "voice.submission.jsonl"), JSON.stringify({ schema_version: 2, receipt }) + "\n");
    expect((await canvas()).narrationStatus).toMatchObject({ state: "inspect", can_generate: false });
    expect((await post("generate", permit.gate_approval_digest)).status).toBe(409);
    expect((await post("resume", permit.gate_approval_digest)).status).toBe(409); expect(runGeneration).toHaveBeenCalledOnce();
    canStart = false;
    const suspended = await post("resume", permit.gate_approval_digest);
    expect(suspended.status).toBe(409); expect(await suspended.json()).toMatchObject({ issue: { code: "viewer_launcher.work_blocked" } });
  }, 30_000);
});
